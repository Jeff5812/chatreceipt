"""Private file storage for uploaded screenshots, pasted conversations and receipt PDFs.

Keys are generated by the application from IDs, never from anything a person typed, and are checked
again here so a path can't escape the storage folder. Files are only ever returned through
authenticated API routes: this folder must not be served by a web server.

``ObjectStorage`` is the interface; a cloud bucket can replace ``LocalStorage`` without other changes.
"""

from __future__ import annotations

import os
import re
import shutil
import tempfile
from pathlib import Path
from typing import Protocol
from uuid import UUID

_KEY = re.compile(r"^[a-z0-9-]+(?:/[a-z0-9.-]+)*$")


class StorageError(Exception):
    """A file couldn't be stored or read. Temporary from the caller's point of view."""


class ObjectStorage(Protocol):
    def put(self, key: str, data: bytes) -> None: ...

    def get(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...

    def delete_prefix(self, prefix: str) -> None: ...


def upload_key(customer_id: UUID, upload_id: UUID) -> str:
    return f"customers/{customer_id}/uploads/{upload_id}"


def receipt_key(customer_id: UUID, receipt_id: UUID) -> str:
    return f"customers/{customer_id}/receipts/{receipt_id}.pdf"


def customer_prefix(customer_id: UUID) -> str:
    return f"customers/{customer_id}"


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self._root = Path(root)

    def _path(self, key: str) -> Path:
        if not _KEY.match(key) or ".." in key:
            raise StorageError("invalid storage key")
        path = (self._root / key).resolve()
        if not path.is_relative_to(self._root.resolve()):
            raise StorageError("invalid storage key")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        try:
            path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
            # Written to a temporary file first, so a crash can't leave half a file under the real name.
            descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=".tmp-")
            try:
                with os.fdopen(descriptor, "wb") as handle:
                    handle.write(data)
                os.replace(temporary, path)
            except BaseException:
                Path(temporary).unlink(missing_ok=True)
                raise
        except OSError as exc:
            raise StorageError(type(exc).__name__) from exc

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except OSError as exc:
            raise StorageError(type(exc).__name__) from exc

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink(missing_ok=True)
        except OSError as exc:
            raise StorageError(type(exc).__name__) from exc

    def delete_prefix(self, prefix: str) -> None:
        try:
            shutil.rmtree(self._path(prefix), ignore_errors=False)
        except FileNotFoundError:
            return
        except OSError as exc:
            raise StorageError(type(exc).__name__) from exc
